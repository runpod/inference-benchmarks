#!/usr/bin/env python3
"""Regenerate an inventory, not an invalid ranking across incompatible trials."""

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    trials = json.loads((ROOT / "results/trials.json").read_text())
    runs = json.loads((ROOT / "results/runs.json").read_text())
    statuses = Counter(t["status"] for t in trials)
    classes = Counter(
        t["recorded"].get("sample_class", "unrecorded") for t in trials if t["status"] == "completed"
    )
    lines = [
        "# Recorded results inventory",
        "",
        "Generated by `python3 tools/summarize_results.py`.",
        "",
        f"Runs: **{len(runs)}**. Recorded trials: **{len(trials)}**.",
        "",
        "## Trial outcomes",
        "",
        "| Status | Trials |",
        "| --- | ---: |",
    ]
    lines += [f"| {k} | {v} |" for k, v in sorted(statuses.items())]
    lines += [
        "",
        "## Completed-trial sample labels",
        "",
        "`unrecorded` means historical metadata is absent, not that the sample was full.",
        "",
        "| Recorded class | Trials |",
        "| --- | ---: |",
    ]
    lines += [f"| {k} | {v} |" for k, v in sorted(classes.items())]
    lines += [
        "",
        "These are mixed historical campaigns, not a matched GPU leaderboard. Completed",
        "does not establish sample adequacy, reliable p99 latency, or correctness certification.",
        "Failures and incomplete trials are coverage outcomes, not zero-throughput measurements.",
        "See [methodology](../docs/METHODOLOGY.md) before comparing any rows.",
        "",
    ]
    (ROOT / "results/SUMMARY.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
